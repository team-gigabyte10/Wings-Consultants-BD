// Runs after `vite build` and the SSR build. Writes 1 HTML file for each route,
// plus 404.html, sitemap.xml, robots.txt and _redirects, into dist/.
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = process.cwd();
const dist = path.join(root, 'dist');
const serverEntry = path.join(root, 'dist-server', 'entry-server.js');

const { render, routes, SITE_URL } = await import(pathToFileURL(serverEntry).href);
const template = await fs.readFile(path.join(dist, 'index.html'), 'utf8');

const escapeAttr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escapeText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** Puts the rendered page and its head values into the template. Fails if a placeholder is missing. */
function fillTemplate(html, head) {
  let out = template;
  // A function replacement, so `$` in the page text is never read as a pattern.
  const replace = (pattern, value) => {
    const found = typeof pattern === 'string' ? out.includes(pattern) : pattern.test(out);
    if (!found) throw new Error(`Template has no match for ${pattern}`);
    out = out.replace(pattern, () => value);
  };

  replace(/<html lang="[^"]*"/, `<html lang="${head.lang}"`);
  replace(/<title>[\s\S]*?<\/title>/, `<title>${escapeText(head.title)}</title>`);
  replace(/<meta property="og:title" content="[^"]*"/, `<meta property="og:title" content="${escapeAttr(head.title)}"`);
  replace(/<meta property="og:image" content="[^"]*"/, `<meta property="og:image" content="${escapeAttr(head.image)}"`);
  if (head.description) {
    replace(/<meta name="description" content="[^"]*"/, `<meta name="description" content="${escapeAttr(head.description)}"`);
    replace(/<meta property="og:description" content="[^"]*"/, `<meta property="og:description" content="${escapeAttr(head.description)}"`);
  }
  if (head.canonical) {
    replace(/<link rel="canonical" href="[^"]*"/, `<link rel="canonical" href="${escapeAttr(head.canonical)}"`);
    replace(/<meta property="og:url" content="[^"]*"/, `<meta property="og:url" content="${escapeAttr(head.canonical)}"`);
  } else {
    replace(/<link rel="canonical"[^>]*>/, '<meta name="robots" content="noindex" />');
    replace(/\s*<meta property="og:url"[^>]*>/, '');
  }
  replace('<div id="root"></div>', `<div id="root">${html}</div>`);
  return out;
}

async function writePage(url, file) {
  const { html, head } = await render(url);
  if (!head) throw new Error(`${url}: the page did not call usePageMeta`);
  const target = path.join(dist, file);
  await fs.mkdir(path.dirname(target), { recursive: true });
  await fs.writeFile(target, fillTemplate(html, head));
}

for (const url of routes) {
  await writePage(url, url === '/' ? 'index.html' : `${url.slice(1)}/index.html`);
}
await writePage('/404-not-found', '404.html');

const today = new Date().toISOString().slice(0, 10);
const loc = (url) => SITE_URL + (url === '/' ? '/' : url);

await fs.writeFile(
  path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${routes.map((u) => `  <url><loc>${loc(u)}</loc><lastmod>${today}</lastmod></url>`).join('\n')}
</urlset>
`
);

await fs.writeFile(path.join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

// Each route is served from its own file. `200!` (forced) stops Netlify from sending a 301
// from `/about` to `/about/`, so the URL stays the same as the canonical URL.
// Any other URL gets the 404 page with status 404.
await fs.writeFile(
  path.join(dist, '_redirects'),
  [
    '# Generated by scripts/prerender.mjs',
    ...routes.filter((u) => u !== '/').map((u) => `${u}  ${u}/index.html  200!`),
    '/*  /404.html  404',
    ''
  ].join('\n')
);

await fs.rm(path.join(root, 'dist-server'), { recursive: true, force: true });
console.log(`Prerendered ${routes.length} routes and 404.html. Wrote sitemap.xml, robots.txt and _redirects.`);
